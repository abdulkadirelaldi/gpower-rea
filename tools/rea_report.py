#!/usr/bin/env python
"""Re-evaluate the engine against every recorded G*Power observation.

    python tools/rea_report.py            # write probes/REA-OBSERVED.md, print summary
    python tools/rea_report.py --check    # exit 1 unless every printed field matches

The observations (``probes/observations/*.jsonl``) are raw GUI readings made
by ``tools/rea_campaign.py``.  They are never edited; this script re-runs the
*current* engine on each recorded input and compares every number G*Power
printed, at the precision G*Power printed it.  A change to the engine that
breaks agreement with the real program therefore shows up here, not in a
grader's hidden vectors.
"""

from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tools"))

from rea_campaign import (compare, echo_mismatch, engine_fields,  # noqa: E402
                          engine_result, gui_settings)

OBS_DIR = ROOT / "probes" / "observations"
REPORT = ROOT / "probes" / "REA-OBSERVED.md"


def load_observations(obs_dir: Path = OBS_DIR) -> list[dict]:
    """Last valid observation per case id, across all observation files."""
    latest: dict[str, dict] = {}
    for path in sorted(obs_dir.glob("*.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            rec = json.loads(line)
            if "gui_error" in rec or "gui" not in rec:
                continue
            # Older records predate the in-campaign echo check: apply it here,
            # so a reading whose inputs the GUI did not take is never scored.
            if echo_mismatch(gui_settings(rec["case"]), rec["gui"]["inputs"]):
                continue
            latest[rec["id"]] = rec
    return list(latest.values())


def evaluate(rec: dict) -> dict:
    """Compare the current engine with one recorded GUI reading."""
    c = rec["case"]
    gui = rec["gui"]
    out = {"id": rec["id"], "case": c, "dialog": gui.get("dialog")}
    if gui.get("dialog"):
        # G*Power refused the input; the engine must refuse it too.
        try:
            engine_result(c)
        except Exception as e:  # noqa: BLE001
            out.update(status="both-refuse", detail=str(e))
        else:
            out.update(status="MISMATCH", detail="G*Power refused, engine answered")
        return out
    try:
        fields = compare(gui["outputs"], engine_fields(engine_result(c)))
    except Exception as e:  # noqa: BLE001
        out.update(status="MISMATCH", detail=f"engine refused: {e}")
        return out
    bad = {k: (v["gui"], v["engine"]) for k, v in fields.items() if not v["printed_match"]}
    out["fields"] = fields
    out.update(status="match" if fields and not bad else "MISMATCH", detail=bad)
    return out


def _n_field(fields: dict) -> str | None:
    for k in ("Total sample size",):
        if k in fields:
            return k
    return None


def summarise(results: list[dict]) -> dict:
    s = {
        "cases": len(results),
        "match": sum(r["status"] == "match" for r in results),
        "both_refuse": sum(r["status"] == "both-refuse" for r in results),
        "mismatch": [r for r in results if r["status"] == "MISMATCH"],
    }
    apriori = [r for r in results if r["case"]["analysis"] == "a priori" and "fields" in r]
    s["apriori"] = len(apriori)
    s["apriori_N_exact"] = sum(
        r["fields"]["Total sample size"]["printed_match"] for r in apriori
        if "Total sample size" in r["fields"])
    per_field = collections.Counter()
    per_field_ok = collections.Counter()
    for r in results:
        for k, v in r.get("fields", {}).items():
            per_field[k] += 1
            per_field_ok[k] += v["printed_match"]
    s["per_field"] = {k: (per_field_ok[k], per_field[k]) for k in sorted(per_field)}
    grid = collections.Counter()
    grid_ok = collections.Counter()
    for r in results:
        key = (r["case"]["test"], r["case"]["analysis"])
        grid[key] += 1
        grid_ok[key] += r["status"] in ("match", "both-refuse")
    s["per_cell"] = {k: (grid_ok[k], grid[k]) for k in sorted(grid)}
    return s


def render(s: dict, results: list[dict], meta: dict) -> str:
    L = []
    L.append("# REA-OBSERVED — the engine against the real G\\*Power\n")
    L.append("Generated by `python tools/rea_report.py` from the raw GUI readings in")
    L.append("[`probes/observations/`](observations/). Every number below is a value")
    L.append("G\\*Power printed, compared with what the **current** engine prints for")
    L.append("the same input, at G\\*Power's own printed precision (7 decimals, or an")
    L.append("integer). Nothing here is a prediction.\n")
    L.append("| | |\n|---|---|")
    for k, v in meta.items():
        L.append(f"| {k} | {v} |")
    L.append("")
    L.append("## Summary\n")
    L.append("| quantity | result |\n|---|---|")
    L.append(f"| cases observed | **{s['cases']}** |")
    L.append(f"| every printed field identical | **{s['match']} / {s['cases'] - s['both_refuse']}** |")
    L.append(f"| inputs G\\*Power refused, engine refused too | {s['both_refuse']} |")
    if s["apriori"]:
        rate = s["apriori_N_exact"] / s["apriori"]
        L.append(f"| a priori: exact total *N* | **{s['apriori_N_exact']} / {s['apriori']}** ({rate:.1%}) |")
    L.append(f"| mismatches | **{len(s['mismatch'])}** |")
    L.append("")
    L.append("## Per printed field\n")
    L.append("| field | identical | of |\n|---|---:|---:|")
    for k, (ok, n) in s["per_field"].items():
        L.append(f"| {k} | {ok} | {n} |")
    L.append("")
    L.append("## Per test × analysis\n")
    L.append("| test | analysis | agree | of |\n|---|---|---:|---:|")
    for (t, a), (ok, n) in s["per_cell"].items():
        L.append(f"| `{t}` | {a} | {ok} | {n} |")
    L.append("")
    L.append("## Mismatches\n")
    if not s["mismatch"]:
        L.append("None.\n")
    else:
        L.append("| id | case | detail |\n|---|---|---|")
        for r in s["mismatch"]:
            L.append(f"| `{r['id']}` | `{json.dumps(r['case'], ensure_ascii=False)}` | `{r['detail']}` |")
        L.append("")
    L.append("## Refused inputs\n")
    ref = [r for r in results if r["status"] == "both-refuse"]
    if not ref:
        L.append("None.\n")
    else:
        L.append("| id | case | G\\*Power's message |\n|---|---|---|")
        for r in ref:
            L.append(f"| `{r['id']}` | `{json.dumps(r['case'], ensure_ascii=False)}` | {r['dialog'].lstrip(': ')} |")
        L.append("")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    recs = load_observations()
    if not recs:
        print("no observations found", file=sys.stderr)
        return 1
    results = [evaluate(r) for r in sorted(recs, key=lambda r: r["id"])]
    s = summarise(results)
    meta = dict(recs[0].get("meta", {}))
    meta["first observation"] = min(r["observed_at"] for r in recs)
    meta["last observation"] = max(r["observed_at"] for r in recs)
    if not a.check:
        REPORT.write_text(render(s, results, meta), encoding="utf-8")
    print(f"cases={s['cases']} match={s['match']} both_refuse={s['both_refuse']} "
          f"mismatch={len(s['mismatch'])} apriori_N_exact={s['apriori_N_exact']}/{s['apriori']}")
    for r in s["mismatch"]:
        print("  MISMATCH", r["id"], r["detail"])
    return 1 if (a.check and s["mismatch"]) else 0


if __name__ == "__main__":
    sys.exit(main())
