#!/usr/bin/env python
"""Write tests/UYUM-RAPORU.md: the differential test of ``gpower-clone``
against every G*Power t2-indep reading in ``oracle/gpower_t2_indep.csv``.

    python tools/uyum_raporu.py

Each oracle row is run through the contract CLI exactly as the course's
harness would run it.  N, n1, n2 must match exactly; actual_power, critical
and ncp to the 4 decimals the contract prints; df exactly.  Refused inputs
must be refused.  Every disagreement is listed with its explanation.
"""

from __future__ import annotations

import contextlib
import csv
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from gpower_rea.clone_cli import main as clone  # noqa: E402

CSV = ROOT / "oracle" / "gpower_t2_indep.csv"
OUT = ROOT / "tests" / "UYUM-RAPORU.md"


def _argv(r: dict) -> list[str]:
    a = ["--test", "t2-indep", "--tails", r["tails"], "--d", r["d"], "--alpha", r["alpha"]]
    if r["mode"] == "a-priori":
        return a + ["--mode", "a-priori", "--power", r["power"], "--ratio", r["ratio"]]
    return a + ["--mode", "post-hoc", "--n1", r["n1_in"], "--n2", r["n2_in"]]


def _run(argv):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = clone(argv)
    return code, json.loads(buf.getvalue())


def main() -> int:
    rows = list(csv.DictReader(CSV.open(encoding="utf-8")))
    res = []
    for r in rows:
        code, got = _run(_argv(r))
        if r["gpower_error"]:
            ok = code != 0 and "error" in got
            res.append((r, ok, "refused by both" if ok else f"G*Power refused, CLI answered {got}", None))
            continue
        big = r["n_total"] and int(r["n_total"]) > 10_000_000
        diffs = []
        if r["mode"] == "a-priori":
            for k in ("n1", "n2", "n_total"):
                if got.get(k) != int(r[k]):
                    diffs.append(f"{k} {got.get(k)} vs {r[k]}")
        for k in ("actual_power", "critical", "ncp"):
            if f"{got.get(k, float('nan')):.4f}" != f"{round(float(r[k]), 4):.4f}":
                diffs.append(f"{k} {got.get(k)} vs {r[k]}")
        if got.get("df") != int(r["df"]):
            diffs.append(f"df {got.get('df')} vs {r['df']}")
        res.append((r, not diffs, "; ".join(diffs), big))
    n = len(res)
    ap = [x for x in res if x[0]["mode"] == "a-priori" and not x[0]["gpower_error"]]
    ap_small = [x for x in ap if not x[3]]
    n_exact = sum(1 for x in ap_small if not any(d.startswith(("n1", "n2", "n_total")) for d in x[2].split("; ") if d))
    full = sum(1 for x in res if x[1])
    L = ["# UYUM-RAPORU — gpower-clone vs G\\*Power, t2-indep", "",
         "Generated by `python tools/uyum_raporu.py`. Every row of",
         "[`oracle/gpower_t2_indep.csv`](../oracle/gpower_t2_indep.csv) (G\\*Power 3.1.9.6",
         "GUI readings) is run through the contract CLI exactly as the course harness",
         "runs it. Tolerance as in the brief: `n1`, `n2`, `n_total`, `df` exact; the",
         "other fields to the 4 decimals the contract prints.", "",
         "| | result |", "|---|---|",
         f"| oracle rows | {n} |",
         f"| **a-priori `N` exact, `N ≤ 1e7`** | **{n_exact} / {len(ap_small)}** ({n_exact / max(1, len(ap_small)):.1%}) |",
         f"| every field within tolerance | {full} / {n} |",
         f"| invalid inputs refused by both | {sum(1 for x in res if x[0]['gpower_error'] and x[1])} / {sum(1 for x in res if x[0]['gpower_error'])} |",
         "", "## Disagreements and their explanation", ""]
    bad = [x for x in res if not x[1]]
    if not bad:
        L.append("None.")
    else:
        L += ["| id | input | difference | explanation |", "|---|---|---|---|"]
        for r, _, d, big in bad:
            why = ("`N > 1e7`: G\\*Power's own N is inexact here (SPEC F-14, E-014; "
                   "arbitrated with 40-digit `mpmath`)") if big else "unexplained"
            L.append(f"| `{r['id']}` | {' '.join(_argv(r)[2:])} | {d} | {why} |")
    L += ["", "The same comparison at G\\*Power's full printed precision (7 decimals), for",
          "all six tests and five analyses, is [`probes/REA-OBSERVED.md`](../probes/REA-OBSERVED.md);",
          "it runs in CI as `tests/test_gpower_observed.py`, and this file's checks as",
          "`tests/test_clone_cli.py` and `tests/test_gherkin_spec.py`.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"{n} rows; a-priori N exact {n_exact}/{len(ap_small)}; within tolerance {full}/{n}; disagreements {len(bad)}")
    return 0 if all(x[3] for x in bad) else 1


if __name__ == "__main__":
    sys.exit(main())
