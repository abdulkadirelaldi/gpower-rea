#!/usr/bin/env python
"""Turn filled-in probe observations into a stamped REA result.

    python tools/harvest.py                 # read probes/probe_worksheet.csv
    python tools/harvest.py --strict        # exit 1 unless every finding is settled

Reads the `observed` column of the worksheet produced by
`tools/probe_plan.py`, compares each observation against the engine's
prediction and against the competing candidate, and writes
`probes/REA-RESULTS.md` with one verdict per SPEC finding.

Comparison rules
----------------
Observations are free text copied out of the GUI, so the comparison is
tolerant about formatting but strict about values:

* every number in the observed string is extracted in order;
* it must contain the same count of numbers as the prediction;
* integers must match exactly; floats must match to 5e-7 (SPEC F-12).

Verdicts
--------
    SUPPORTS      observation matches the engine, and differs from the
                  competing candidate (a real discrimination)
    CONTRADICTS   observation matches the competing candidate
    AMBIGUOUS     observation matches both (a control row, or the candidates
                  happen to coincide)
    UNEXPLAINED   observation matches neither -- the most interesting outcome,
                  because it means a third behaviour exists
    PENDING       no observation entered yet
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORKSHEET = ROOT / "probes" / "probe_worksheet.csv"
RESULTS = ROOT / "probes" / "REA-RESULTS.md"

NUMBER = re.compile(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?")
POWER_TOL = 5e-7


def _numbers(text: str) -> list[str]:
    return NUMBER.findall(text or "")


def _same(observed: str, predicted: str) -> bool | None:
    """True / False, or None when the prediction is not numeric."""
    pred = _numbers(predicted)
    obs = _numbers(observed)
    if not pred:
        return None
    if len(pred) != len(obs):
        return False
    for p, o in zip(pred, obs):
        pf, of = float(p), float(o)
        is_int = "." not in p and "e" not in p.lower()
        if is_int:
            if int(round(pf)) != int(round(of)):
                return False
        elif abs(pf - of) > POWER_TOL * max(1.0, abs(pf)):
            return False
    return True


def classify(row: dict) -> str:
    observed = (row.get("observed") or "").strip()
    if not observed:
        return "PENDING"
    hit_engine = _same(observed, row["engine_prediction"])
    hit_other = _same(observed, row["competing_prediction"])
    if hit_engine is None:
        return "PENDING"
    if hit_engine and not hit_other:
        return "SUPPORTS"
    if hit_engine and hit_other:
        return "AMBIGUOUS"
    if hit_other:
        return "CONTRADICTS"
    return "UNEXPLAINED"


def finding_verdict(verdicts: list[str]) -> str:
    if "CONTRADICTS" in verdicts:
        return "CONTRADICTED — the competing candidate matches; fix the engine"
    if "UNEXPLAINED" in verdicts:
        return "UNEXPLAINED — a third behaviour exists; widen the candidate set"
    if "SUPPORTS" in verdicts:
        if "PENDING" in verdicts:
            return "SUPPORTED (partially stamped)"
        return "SUPPORTED by discriminating observation"
    if all(v == "PENDING" for v in verdicts):
        return "PENDING — no observation entered"
    return "NOT DISCRIMINATED — only control rows observed"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--strict", action="store_true",
                    help="exit 1 unless every finding is settled")
    ap.add_argument("--worksheet", default=str(WORKSHEET))
    args = ap.parse_args()

    path = Path(args.worksheet)
    if not path.is_file():
        sys.stderr.write(
            f"worksheet not found: {path}\n"
            "run `python tools/probe_plan.py` first\n"
        )
        return 2

    with path.open(encoding="utf-8-sig", newline="") as fh:
        rows = [dict(r) for r in csv.DictReader(fh)]
    if not rows:
        sys.stderr.write("worksheet is empty\n")
        return 2

    by_finding: dict[str, list[tuple[dict, str]]] = defaultdict(list)
    counts: dict[str, int] = defaultdict(int)
    for row in rows:
        verdict = classify(row)
        counts[verdict] += 1
        by_finding[row["finding"]].append((row, verdict))

    lines = [
        "# REA probe results",
        "",
        "Generated by `python tools/harvest.py` from "
        "`probes/probe_worksheet.csv`.",
        "",
        "| verdict | rows |",
        "|---|---|",
    ]
    for key in ("SUPPORTS", "AMBIGUOUS", "CONTRADICTS", "UNEXPLAINED", "PENDING"):
        lines.append(f"| {key} | {counts.get(key, 0)} |")
    lines += ["", "## Per-finding verdict", "",
              "| finding | verdict | discriminating rows observed |", "|---|---|---|"]
    for finding in sorted(by_finding):
        entries = by_finding[finding]
        verdicts = [v for _, v in entries]
        observed_disc = sum(
            1 for r, v in entries
            if r["discriminates"] == "yes" and v != "PENDING"
        )
        total_disc = sum(1 for r, _ in entries if r["discriminates"] == "yes")
        lines.append(
            f"| {finding} | {finding_verdict(verdicts)} | "
            f"{observed_disc}/{total_disc} |"
        )

    lines += ["", "## Row detail", "",
              "| probe | finding | verdict | observed | engine | competing |",
              "|---|---|---|---|---|---|"]
    for row in rows:
        verdict = classify(row)
        obs = (row.get("observed") or "").strip() or "—"
        lines.append(
            f"| `{row['probe_id']}` | {row['finding']} | {verdict} | "
            f"`{obs}` | `{row['engine_prediction']}` | "
            f"`{row['competing_prediction']}` |"
        )

    unsettled = [
        f for f, entries in by_finding.items()
        if finding_verdict([v for _, v in entries]).startswith(("PENDING", "NOT"))
    ]
    if unsettled:
        lines += [
            "",
            "## Still unsettled",
            "",
            "The following findings have no discriminating observation yet. "
            "They remain `REA-OPEN` in SPEC.md until one is entered:",
            "",
        ]
        lines += [f"- {f}" for f in sorted(unsettled)]

    RESULTS.parent.mkdir(exist_ok=True)
    RESULTS.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    print(f"wrote {RESULTS}")
    for key in ("SUPPORTS", "AMBIGUOUS", "CONTRADICTS", "UNEXPLAINED", "PENDING"):
        print(f"  {key:<12} {counts.get(key, 0)}")
    if counts.get("CONTRADICTS") or counts.get("UNEXPLAINED"):
        print("\nATTENTION: at least one observation does not match the engine.")
        print("Read probes/REA-RESULTS.md before trusting any output.")
        return 1
    if args.strict and unsettled:
        print(f"\n--strict: {len(unsettled)} finding(s) still unsettled")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
